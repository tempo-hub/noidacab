/**
 * Global pricing formula: (distance * 1.5 * cabprice) + 500
 */
export function calculateRouteStartingFare(distanceStr: string, perKmStr: string = "10"): string {
  const dist = parseFloat(distanceStr.replace(/[^0-9.]/g, "")) || 0;
  const rate = parseFloat(perKmStr.replace(/[^0-9.]/g, "")) || 10;
  if (!dist) return "₹1,499";
  const fare = Math.round(dist * 1.5 * rate + 500);
  return `₹${fare.toLocaleString("en-IN")}`;
}

